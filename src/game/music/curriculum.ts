const SEMITONES: Record<Pitch['letter'], number> = { C: 0, D: 2, E: 4, F: 5, G: 7, A: 9, B: 11 };

export function curriculumPitch(name: string, centsOffset = 0): Pitch {
  const match = /^([A-G])([#b]{0,2})(-?\d+)$/.exec(name);
  if (!match) throw new Error(`음 철자를 읽을 수 없습니다: ${name}`);
  const letter = match[1] as Pitch['letter'];
  const accidental = [...match[2]].reduce((sum, sign) => sum + (sign === '#' ? 1 : -1), 0);
  const octave = Number(match[3]);
  return { id: centsOffset ? `${name}@${centsOffset}` : name, letter, accidental, octave,
    midi: 12 * (octave + 1) + SEMITONES[letter] + accidental,
    ...(centsOffset ? { centsOffset } : {}) };
}

